
BEGIN;

CREATE SCHEMA IF NOT EXISTS food_bank;
SET LOCAL search_path TO food_bank, public;

CREATE TABLE IF NOT EXISTS users (
    user_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    email         VARCHAR(150) NOT NULL UNIQUE,
    phone         VARCHAR(20) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(20) NOT NULL
                  CHECK (role IN ('Donor', 'Recipient', 'Volunteer', 'Coordinator')),
    failed_logins SMALLINT NOT NULL DEFAULT 0 CHECK (failed_logins >= 0),
    locked_until  TIMESTAMP NULL,
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);


CREATE TABLE IF NOT EXISTS recipients (
    recipient_id         INTEGER PRIMARY KEY
                         REFERENCES users(user_id) ON DELETE RESTRICT,
    household_size       INTEGER NOT NULL CHECK (household_size > 0),
    dietary_restrictions VARCHAR(255),
    emergency_contact    VARCHAR(150) NOT NULL,
    approval_status      VARCHAR(12) NOT NULL DEFAULT 'Pending'
                         CHECK (approval_status IN ('Pending', 'Approved', 'Rejected')),
    approved_by          INTEGER REFERENCES users(user_id) ON DELETE RESTRICT,
    approved_at          TIMESTAMP NULL
);


CREATE TABLE IF NOT EXISTS volunteers (
    volunteer_id  INTEGER PRIMARY KEY
                  REFERENCES users(user_id) ON DELETE RESTRICT,
    profile_image VARCHAR(255),
    availability  VARCHAR(255),
    created_by    INTEGER REFERENCES users(user_id) ON DELETE RESTRICT
);


CREATE TABLE IF NOT EXISTS categories (
    category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(50) NOT NULL UNIQUE
);


CREATE TABLE IF NOT EXISTS donations (
    donation_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donor_id      INTEGER NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    recorded_by   INTEGER REFERENCES volunteers(volunteer_id) ON DELETE RESTRICT,
    item_name     VARCHAR(100) NOT NULL,
    category_id   INTEGER NOT NULL REFERENCES categories(category_id) ON DELETE RESTRICT,
    quantity      NUMERIC(10,2) NOT NULL CHECK (quantity >= 0),
    unit          VARCHAR(20) NOT NULL,
    donation_date DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS inventory (
    inventory_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    donation_id       INTEGER REFERENCES donations(donation_id) ON DELETE RESTRICT,
    item_name         VARCHAR(100) NOT NULL,
    category_id       INTEGER NOT NULL REFERENCES categories(category_id) ON DELETE RESTRICT,
    quantity          NUMERIC(10,2) NOT NULL CHECK (quantity >= 0),
    quantity_received NUMERIC(10,2) NOT NULL CHECK (quantity_received >= 0),
    unit              VARCHAR(20) NOT NULL,
    received_date     DATE NOT NULL,
    expiry_date       DATE,
    waste_date        DATE,
    status            VARCHAR(12) NOT NULL DEFAULT 'Available'
                      CHECK (status IN ('Available', 'Distributed', 'Expired', 'Discarded')),
    updated_by        INTEGER REFERENCES users(user_id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS hamper_requests (
    request_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id INTEGER NOT NULL REFERENCES recipients(recipient_id) ON DELETE RESTRICT,
    request_date DATE NOT NULL,
    pickup_date  DATE NOT NULL,
    status       VARCHAR(12) NOT NULL DEFAULT 'Requested'
                 CHECK (status IN ('Requested', 'Scheduled', 'Completed', 'Cancelled'))
);


CREATE TABLE IF NOT EXISTS volunteer_shifts (
    shift_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    volunteer_id  INTEGER NOT NULL REFERENCES volunteers(volunteer_id) ON DELETE RESTRICT,
    shift_date    DATE NOT NULL,
    start_time    TIME NOT NULL,
    end_time      TIME NOT NULL,
    assigned_task VARCHAR(100) NOT NULL,
    assigned_by   INTEGER NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    CONSTRAINT chk_shift_times CHECK (end_time > start_time)
);

CREATE TABLE IF NOT EXISTS distributions (
    distribution_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id        INTEGER UNIQUE REFERENCES hamper_requests(request_id) ON DELETE RESTRICT,
    recipient_id      INTEGER NOT NULL REFERENCES recipients(recipient_id) ON DELETE RESTRICT,
    volunteer_id      INTEGER NOT NULL REFERENCES volunteers(volunteer_id) ON DELETE RESTRICT,
    shift_id          INTEGER REFERENCES volunteer_shifts(shift_id) ON DELETE RESTRICT,
    distribution_date DATE NOT NULL,
    distribution_time TIME NOT NULL,
    pickup_status     VARCHAR(12) NOT NULL DEFAULT 'Scheduled'
                      CHECK (pickup_status IN ('Scheduled', 'Fulfilled', 'Missed', 'Delayed'))
);


CREATE TABLE IF NOT EXISTS distribution_items (
    distribution_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    distribution_id      INTEGER NOT NULL REFERENCES distributions(distribution_id) ON DELETE CASCADE,
    inventory_id         INTEGER NOT NULL REFERENCES inventory(inventory_id) ON DELETE RESTRICT,
    quantity             NUMERIC(10,2) NOT NULL CHECK (quantity > 0),
    unit                 VARCHAR(20) NOT NULL
);


CREATE TABLE IF NOT EXISTS notifications (
    notification_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type            VARCHAR(20) NOT NULL
                    CHECK (type IN ('PickupAlert', 'InventoryAtRisk')),
    risk_reason     VARCHAR(20) NOT NULL
                    CHECK (risk_reason IN ('Missed', 'Delayed', 'Expiry', 'StockDecline')),
    distribution_id INTEGER REFERENCES distributions(distribution_id) ON DELETE RESTRICT,
    inventory_id    INTEGER REFERENCES inventory(inventory_id) ON DELETE RESTRICT,
    category_id     INTEGER REFERENCES categories(category_id) ON DELETE RESTRICT,
    recipient_email VARCHAR(150) NOT NULL,
    message         TEXT NOT NULL,
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    sent_status     VARCHAR(10) NOT NULL DEFAULT 'Pending'
                    CHECK (sent_status IN ('Pending', 'Sent', 'Failed'))
);


COMMIT;
